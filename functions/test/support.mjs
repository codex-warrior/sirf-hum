// Test-only helpers: deterministic Ed25519 keys and certificates built per
// the D-064 / D-070 formats, using node:crypto (no custom primitives).
// Runs against the compiled output (`npm run build` first).
import { Buffer } from 'node:buffer';
import { createPrivateKey, createPublicKey, sign } from 'node:crypto';
import certModule from '../lib/device/certificate.js';
import proofModule from '../lib/device/proof.js';
import statementsModule from '../lib/device/statements.js';

const { certificateSignedPayload, lengthPrefixed } = certModule;
const { deviceProofPayload, ProofPurpose } = proofModule;
const { approvalCode, approvalPayload, recoveryApprovalPayload, recoveryRegistrationPayload } = statementsModule;

// DER PKCS#8 prefix for a raw 32-byte Ed25519 seed (RFC 8410).
const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');

export function keyFromSeed(seed) {
  const privateKey = createPrivateKey({
    key: Buffer.concat([PKCS8_PREFIX, Buffer.from(seed)]),
    format: 'der',
    type: 'pkcs8',
  });
  const spki = createPublicKey(privateKey).export({ format: 'der', type: 'spki' });
  return { privateKey, publicKey: Buffer.from(spki.subarray(spki.length - 32)) };
}

export const seed = (byte) => Buffer.alloc(32, byte);

/** Encodes a v1 device certificate signed by `person`. */
export function makeCertificate({ person, device, deviceId, issuedAt = 1_760_000_000n }) {
  const fields = {
    personKey: person.publicKey,
    deviceId: Buffer.from(deviceId),
    deviceSignatureKey: device.publicKey,
    issuedAtUnix: issuedAt,
  };
  const signature = sign(null, certificateSignedPayload(fields), person.privateKey);
  const issued = Buffer.alloc(8);
  issued.writeBigUInt64BE(issuedAt, 0);
  return Buffer.concat([
    Buffer.from([1]),
    lengthPrefixed(fields.personKey),
    fields.deviceId,
    lengthPrefixed(fields.deviceSignatureKey),
    issued,
    lengthPrefixed(signature),
  ]);
}

export function makeProof({ device, accountId, deviceId, certificate, challenge, purpose = ProofPurpose.activation }) {
  const payload = deviceProofPayload(purpose, accountId, Buffer.from(deviceId), certificate, Buffer.from(challenge));
  return { payload, signature: sign(null, payload, device.privateKey) };
}

/** The committed golden vector, rebuilt from fixed seeds. */
export function goldenVector() {
  const person = keyFromSeed(seed(0x11));
  const device = keyFromSeed(seed(0x22));
  const deviceId = Buffer.from('00112233445566778899aabbccddeeff', 'hex');
  const accountId = 'vectorAccount01';
  const challenge = Buffer.alloc(32, 0x5a);
  const certificate = makeCertificate({ person, device, deviceId });
  const { payload, signature } = makeProof({ device, accountId, deviceId, certificate, challenge });
  return {
    description:
      'Device proof v1 (D-070) over a v1 device certificate (D-064). Generated by functions/test/vectors/generate.mjs from fixed seeds; verified by functions and Rust tests.',
    accountId,
    deviceIdHex: deviceId.toString('hex'),
    certificateHex: certificate.toString('hex'),
    challengeHex: challenge.toString('hex'),
    signatureHex: signature.toString('hex'),
    payloadHex: payload.toString('hex'),
  };
}

/** A device's own key material (independent PIK + device key, D-074). */
export function makeDevice(personSeed, deviceSeed, deviceIdHex) {
  const person = keyFromSeed(seed(personSeed));
  const device = keyFromSeed(seed(deviceSeed));
  const deviceId = Buffer.from(deviceIdHex, 'hex');
  return { person, device, deviceId, certificate: makeCertificate({ person, device, deviceId }) };
}

/** Approval statement signed by the approver's PIK (D-075). */
export function makeApproval({ approver, newDevice, accountId, challenge, expiresAtUnix, signer = approver.person }) {
  const payload = approvalPayload(accountId, approver.certificate, newDevice.certificate, Buffer.from(challenge), expiresAtUnix);
  return { payload, signature: sign(null, payload, signer.privateKey) };
}

export function makeRecoveryRegistration({ registrar, recovery, accountId, challenge, expiresAtUnix, signer = registrar.person }) {
  const payload = recoveryRegistrationPayload(accountId, registrar.certificate, recovery.publicKey, Buffer.from(challenge), expiresAtUnix);
  return { payload, signature: sign(null, payload, signer.privateKey) };
}

export function makeRecoveryApproval({ recovery, newDevice, accountId, challenge, expiresAtUnix, signer = recovery }) {
  const payload = recoveryApprovalPayload(accountId, recovery.publicKey, newDevice.certificate, Buffer.from(challenge), expiresAtUnix);
  return { payload, signature: sign(null, payload, signer.privateKey) };
}

/** Golden vectors for the Prompt 08 statements (verified by Rust tests). */
export function trustVectors() {
  const accountId = 'vectorAccount01';
  const approver = makeDevice(0x31, 0x32, '0102030405060708090a0b0c0d0e0f10');
  const newDevice = makeDevice(0x41, 0x42, 'a1a2a3a4a5a6a7a8a9aaabacadaeafb0');
  const recovery = keyFromSeed(seed(0x51));
  const challenge = Buffer.alloc(32, 0x6b);
  const expiresAtUnix = 1_760_000_600;
  const approval = makeApproval({ approver, newDevice, accountId, challenge, expiresAtUnix });
  const registration = makeRecoveryRegistration({ registrar: approver, recovery, accountId, challenge, expiresAtUnix });
  const recoveryApproval = makeRecoveryApproval({ recovery, newDevice, accountId, challenge, expiresAtUnix });
  return {
    description:
      'Device approval, recovery key registration and recovery approval v1 (D-075, D-076). Generated by functions/test/vectors/generate.mjs from fixed seeds; verified by functions and Rust tests.',
    accountId,
    approverCertificateHex: approver.certificate.toString('hex'),
    newCertificateHex: newDevice.certificate.toString('hex'),
    recoveryPublicKeyHex: recovery.publicKey.toString('hex'),
    recoverySeedHex: seed(0x51).toString('hex'),
    challengeHex: challenge.toString('hex'),
    expiresAtUnix: String(expiresAtUnix),
    approvalSignatureHex: approval.signature.toString('hex'),
    approvalPayloadHex: approval.payload.toString('hex'),
    registrationSignatureHex: registration.signature.toString('hex'),
    registrationPayloadHex: registration.payload.toString('hex'),
    recoverySignatureHex: recoveryApproval.signature.toString('hex'),
    recoveryPayloadHex: recoveryApproval.payload.toString('hex'),
    approvalCode: String(approvalCode(newDevice.certificate, challenge)).padStart(6, '0'),
  };
}
